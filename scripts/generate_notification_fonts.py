#!/usr/bin/env python3
"""Generate native-size notification fonts without changing dashboard assets."""
import argparse
from pathlib import Path
from generate_vlw_font import array_text, generate_vlw


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    arrays = '\n'.join(array_text(f'kSpaceMono{size}Vlw', generate_vlw(args.font, size))
                       for size in (14, 15, 22, 24, 36))
    args.output.write_text('// Generated by scripts/generate_notification_fonts.py. Do not edit manually.\n'
                          '#pragma once\n#include <cstdint>\n'
                          'namespace task_notification { namespace font_data {\n' + arrays +
                          '\n} } // namespace task_notification::font_data\n')


if __name__ == '__main__':
    main()
